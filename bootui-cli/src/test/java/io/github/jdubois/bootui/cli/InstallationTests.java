package io.github.jdubois.bootui.cli;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class InstallationTests {
    @TempDir
    Path directory;

    @Test
    void recognizesRecordedAndLegacyLaunchersIncludingWindowsAndSpaces() throws Exception {
        for (boolean windows : new boolean[] {false, true}) {
            for (boolean record : new boolean[] {false, true}) {
                var target = UpdateTestRepository.install(
                        directory.resolve("custom path " + windows + record),
                        ReleaseRepository.DEFAULT,
                        record,
                        windows);
                assertThat(Installation.detect(
                                target.jar(),
                                Map.of("PATH", target.launcher().getParent().toString())))
                        .isEqualTo(target);
            }
        }
    }

    @Test
    void environmentOrAMavenCacheDoesNotEstablishWriteOwnership() throws Exception {
        Path jar = directory.resolve("repository/bootui.jar");
        Files.createDirectories(jar.getParent());
        Files.write(jar, UpdateTestRepository.jar("1.0.0"));
        assertThat(Installation.detect(
                                jar,
                                Map.of("BOOTUI_INSTALL_DIR", jar.getParent().toString()))
                        .kind())
                .isEqualTo("unmanaged");
        assertThat(Installation.detect(directory, Map.of()).kind()).isEqualTo("unmanaged");
    }

    @Test
    void jbangNeedsCacheAndMatchingLauncherEvidenceAndNeverClaimsInstallerOwnership() throws Exception {
        Path jar = directory.resolve("cache/jars/bootui.jar");
        Files.createDirectories(jar.getParent());
        Files.write(jar, UpdateTestRepository.jar("1.0.0"));
        Path bin = Files.createDirectory(directory.resolve("bin"));
        Files.writeString(bin.resolve("bootui"), "#!/bin/sh\nexec jbang run bootui@jdubois/boot-ui \"$@\"\n");
        assertThat(Installation.detect(jar, Map.of("PATH", bin.toString())).kind())
                .isEqualTo("jbang");
    }

    @Test
    void mismatchedRecordsAndAlteredLaunchersFailClosed() throws Exception {
        var target = UpdateTestRepository.install(directory, ReleaseRepository.DEFAULT, true, false);
        Files.writeString(target.launcher(), "#!/bin/sh\njava -jar something-else.jar\n");
        assertThatThrownBy(() -> Installation.detect(target.jar(), Map.of())).hasMessageContaining("does not match");
        Files.writeString(directory.resolve(Installation.RECORD), "future-format\n");
        assertThatThrownBy(() -> Installation.detect(target.jar(), Map.of())).hasMessageContaining("Unrecognized");
    }

    @Test
    @org.junit.jupiter.api.condition.DisabledOnOs(org.junit.jupiter.api.condition.OS.WINDOWS)
    void aSymlinkedCodeSourceIsNotAutomaticallyOwned() throws Exception {
        var target = UpdateTestRepository.install(directory, ReleaseRepository.DEFAULT, true, false);
        Path alias = directory.resolve("alias.jar");
        Files.createSymbolicLink(alias, target.jar());
        assertThat(Installation.detect(alias, Map.of()).kind()).isEqualTo("unmanaged");
    }

    @Test
    void recognizesWindowsPathCasingForLegacyAndJbangLaunchers() throws Exception {
        var target = UpdateTestRepository.install(directory.resolve("legacy"), ReleaseRepository.DEFAULT, false, true);
        assertThat(Installation.detect(
                        target.jar(),
                        Map.of("Path", target.launcher().getParent().toString())))
                .isEqualTo(target);
        Path jar = directory.resolve("cache/jars/bootui.jar");
        Files.createDirectories(jar.getParent());
        Files.write(jar, UpdateTestRepository.jar("1.0.0"));
        Path bin = Files.createDirectory(directory.resolve("jbang-bin"));
        Files.writeString(bin.resolve("bootui.cmd"), "@echo off\r\njbang run bootui@jdubois/boot-ui %*\r\n");
        assertThat(Installation.detect(jar, Map.of("Path", bin.toString())).kind())
                .isEqualTo("jbang");
    }

    @Test
    void staleAndOversizedUnrelatedLaunchersCannotHideTheMatchingLegacyLauncher() throws Exception {
        var target = UpdateTestRepository.install(directory.resolve("legacy"), ReleaseRepository.DEFAULT, false, false);
        Path stale = Files.createDirectory(directory.resolve("stale"));
        Files.writeString(
                stale.resolve("bootui"),
                "# Generated by the BootUI CLI installer.\nJAR=\"" + directory.resolve("deleted.jar") + "\"\n");
        Path binary = Files.createDirectory(directory.resolve("binary"));
        Files.write(binary.resolve("bootui"), new byte[16385]);
        String path = stale + java.io.File.pathSeparator + binary + java.io.File.pathSeparator + "\""
                + target.launcher().getParent() + "\"";
        assertThat(Installation.detect(target.jar(), Map.of("PATH", path))).isEqualTo(target);
    }

    @Test
    void staleRecordedJarGetsTheCanonicalMismatchError() throws Exception {
        var target = UpdateTestRepository.install(directory, ReleaseRepository.DEFAULT, true, false);
        Files.writeString(
                directory.resolve(Installation.RECORD),
                "bootui-install-v1\n" + directory.resolve("deleted.jar") + "\n" + target.launcher() + "\n"
                        + ReleaseRepository.DEFAULT + "\n");
        assertThatThrownBy(() -> Installation.detect(target.jar(), Map.of())).hasMessageContaining("does not match");
    }

    @Test
    void installationRecordsMustBeRegularFilesNotDirectories() throws Exception {
        var target = UpdateTestRepository.install(directory, ReleaseRepository.DEFAULT, false, false);
        Files.createDirectory(directory.resolve(Installation.RECORD));
        assertThatThrownBy(() -> Installation.detect(target.jar(), Map.of())).hasMessageContaining("Unrecognized");
    }

    @Test
    @org.junit.jupiter.api.condition.DisabledOnOs(org.junit.jupiter.api.condition.OS.WINDOWS)
    void installationRecordsMustNotBeSymlinks() throws Exception {
        var target = UpdateTestRepository.install(directory, ReleaseRepository.DEFAULT, false, false);
        Path other = directory.resolve("other-record");
        Files.writeString(
                other,
                "bootui-install-v1\n" + target.jar() + "\n" + target.launcher() + "\n" + ReleaseRepository.DEFAULT
                        + "\n");
        Files.createSymbolicLink(directory.resolve(Installation.RECORD), other);
        assertThatThrownBy(() -> Installation.detect(target.jar(), Map.of())).hasMessageContaining("Unrecognized");
    }
}
