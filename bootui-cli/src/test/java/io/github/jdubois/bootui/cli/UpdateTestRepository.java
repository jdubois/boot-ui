package io.github.jdubois.bootui.cli;

import com.sun.net.httpserver.HttpServer;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.net.InetSocketAddress;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.HexFormat;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.CopyOnWriteArrayList;
import java.util.jar.Attributes;
import java.util.jar.JarEntry;
import java.util.jar.JarOutputStream;
import java.util.jar.Manifest;

final class UpdateTestRepository implements AutoCloseable {
    final Map<String, byte[]> responses = new ConcurrentHashMap<>();
    final Map<String, Integer> statuses = new ConcurrentHashMap<>();
    final List<String> requests = new CopyOnWriteArrayList<>();
    final HttpServer server;

    UpdateTestRepository() throws IOException {
        server = HttpServer.create(new InetSocketAddress("127.0.0.1", 0), 0);
        server.createContext("/", exchange -> {
            String path = exchange.getRequestURI().getPath();
            requests.add(path);
            byte[] body = responses.getOrDefault(path, new byte[0]);
            int status = statuses.getOrDefault(path, responses.containsKey(path) ? 200 : 404);
            exchange.sendResponseHeaders(status, body.length == 0 ? -1 : body.length);
            exchange.getResponseBody().write(body);
            exchange.close();
        });
        server.start();
    }

    String url() {
        return "http://127.0.0.1:" + server.getAddress().getPort();
    }

    void metadata(String version) {
        put("maven-metadata.xml", "<metadata><versioning><release>" + version + "</release></versioning></metadata>");
    }

    void put(String path, String content) {
        responses.put(ReleaseRepository.ARTIFACT_PATH + path, content.getBytes(StandardCharsets.UTF_8));
    }

    void artifact(String version, byte[] bytes, String algorithm) throws Exception {
        String path = ReleaseRepository.ARTIFACT_PATH + version + "/bootui-cli-" + version + "-all.jar";
        responses.put(path, bytes);
        responses.put(
                path + "." + algorithm.toLowerCase(java.util.Locale.ROOT).replace("-", ""),
                HexFormat.of()
                        .formatHex(MessageDigest.getInstance(algorithm).digest(bytes))
                        .getBytes(StandardCharsets.UTF_8));
    }

    static byte[] jar(String version) throws IOException {
        Manifest manifest = new Manifest();
        Attributes attributes = manifest.getMainAttributes();
        attributes.putValue("Manifest-Version", "1.0");
        attributes.putValue("Main-Class", BootUiCli.class.getName());
        attributes.putValue("Implementation-Version", version);
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        try (JarOutputStream jar = new JarOutputStream(bytes, manifest)) {
            jar.putNextEntry(new JarEntry("io/github/jdubois/bootui/cli/BootUiCli.class"));
            jar.write(new byte[] {1, 2, 3});
            jar.closeEntry();
        }
        return bytes.toByteArray();
    }

    static Installation install(Path directory, String repository, boolean record, boolean windows) throws IOException {
        Files.createDirectories(directory);
        Path jar = directory.resolve("bootui-cli-1.0.0-all.jar");
        Files.write(jar, jar("1.0.0"));
        Path launcher = directory.resolve(windows ? "bootui.cmd" : "bootui");
        Files.writeString(
                launcher,
                windows
                        ? "@echo off\r\nrem Generated by the BootUI CLI installer.\r\nset \"BOOTUI_JAR=" + jar
                                + "\"\r\n"
                        : "#!/bin/sh\n# Generated by the BootUI CLI installer.\nJAR=\"" + jar + "\"\n");
        if (record) {
            Files.writeString(
                    directory.resolve(Installation.RECORD),
                    "bootui-install-v1\n" + jar + "\n" + launcher + "\n" + repository + "\n");
        }
        return new Installation("installer", jar.toRealPath(), launcher.toRealPath(), record ? repository : null);
    }

    @Override
    public void close() {
        server.stop(0);
    }
}
